COURSE_DATA_VERSION = '2026-07-v1'


def init_course_data(db):
    """初始化课程表数据到数据库

    策略：如果数据库中已有课程数据（courses 表不为空），则完全跳过，
    保留用户的自定义数据；只有在完全为空时才批量插入默认课程。
    这样可以避免每次版本变化或重新部署时覆盖用户已有的课程、
    习惯打卡和学习日志等数据。
    """
    conn = db.get_connection()
    cursor = conn.cursor()

    # 1. 检查 courses 表是否已有数据：已有则直接跳过，保留用户数据
    cursor.execute("SELECT COUNT(*) FROM courses")
    course_count = cursor.fetchone()[0]
    if course_count > 0:
        # 已有课程数据：不做任何删除/覆盖操作，直接返回
        conn.close()
        return

    # 2. courses 为空（全新数据库）：批量插入默认课程
    for course in COURSE_SCHEDULE:
        cursor.execute('''
            INSERT INTO courses
            (date, weekday, title, course_type, start_time, end_time, description, is_rest, is_self_study)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        ''', (
            course.get('date'), course.get('weekday'), course.get('title'),
            course.get('course_type', 'lecture'), course.get('start_time'),
            course.get('end_time'), course.get('description'),
            course.get('is_rest', 0), course.get('is_self_study', 0)
        ))

    # 3. 记录初始化标识（仅首次，后续永远不会再自动执行初始化）
    cursor.execute(
        "INSERT OR REPLACE INTO app_meta (key, value) VALUES (?, ?)",
        ('course_data_version', COURSE_DATA_VERSION)
    )
    cursor.execute(
        "INSERT OR REPLACE INTO app_meta (key, value) VALUES (?, ?)",
        ('initial_completed', '1')
    )

    conn.commit()
    conn.close()
